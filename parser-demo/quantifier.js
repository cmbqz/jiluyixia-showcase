/**
 * quantifier.js —— 量词剥除：为什么必须用白名单，不能用黑名单
 *
 * 这是一个从真实记账小程序里抽出来的最小可跑示例。
 * 目标：说明一个具体的取舍——「量词到底剥不剥」不该用黑名单判断。
 *
 * ── 问题 ───────────────────────────────────────────────────
 * 用户输入「买了一杯咖啡15」，理想结果是「咖啡」。
 * 但输入也可能是「买了盒仔茶12」、「买了盒月饼68」、「盘心20」。
 *
 * 第一版用黑名单：列出「哪些量词不能剥」。
 * 失败了，因为黑名单是开放集合，永远有表外说法击穿它：
 *   「盒仔茶」→ 剥掉「盒」→ 「仔茶」（商品名被毁，原信息不可恢复）
 *
 * ── 修法 ───────────────────────────────────────────────────
 * 方向反转：不枚举「哪些不能剥」，只剥「能确认该剥的」。
 *
 * 每次最多剥掉一层量词槽，三选一：
 *   (a) 数词 + 量词        「一杯咖啡」→「咖啡」
 *   (b) 「个」             「一个苹果」→「苹果」
 *   (c) 量词 + 品类白名单   「盒月饼」→「月饼」，但「盒仔茶」不动
 *
 * ── 为什么 (a) 可以无条件剥，而 (c) 必须查白名单 ────────────
 * 因为剥掉之后名字是否还能认出来：
 *   「一杯茅台」→「茅台」   仍然可读，不剥反而是噪音
 *   「盒仔茶」  →「仔茶」   完全失去词义
 * 有数词时，量词是修饰；没数词时，量词可能已经是词的一部分。
 *
 * ── 代价不对称 ─────────────────────────────────────────────
 *   漏剥（该剥没剥）→ 名称多个量词，观感差，用户能改。可逆。
 *   误剥（不该剥剥了）→ 商品名损坏，原始信息丢失。不可逆。
 * 两类错误代价不对称时，默认选代价小的那一侧。
 *
 * ── 明确不处理的范围 ───────────────────────────────────────
 * 本 demo 只认「名称 + 末尾金额」这一种输入形态。
 * 真实引擎要处理几十种位置组合（金额在前 / 居中 / 多笔 / 带单位 / 带规格），
 * 还叠着日期归一、多事件切分、分类判定。这里刻意只保留量词这一层。
 */

"use strict";

/* ── 量词 → 它真会计量的品类名词（节选自真实词表，完整版 19 组）── */
const QW_NOUN = {
  "杯": "咖啡|奶茶|水|豆浆|果汁|可乐|茶|酸奶|冰淇淋|酒|牛奶|珍珠奶茶",
  "瓶": "水|饮料|可乐|啤酒|洗发水|沐浴露|牛奶|油|酱油|醋|矿泉水|酒",
  "罐": "可乐|啤酒|奶粉|饮料|咖啡|红牛",
  "盒": "牛奶|月饼|鸡蛋|饼干|巧克力|药|纸巾|酸奶|蛋糕|冰淇淋|草莓|蓝莓|车厘子|葡萄|寿司|便当|水果",
  "碗": "面|牛肉面|拉面|饭|汤|粥|米饭|馄饨|饺子|粉|米线|麻辣烫",
  "盘": "炒饭|菜|水果|饺子|虾|烤肉|凉菜|点心|炒面|炒粉",
  "碟": "小菜|花生米|花生|咸菜|酱料",
  "桶": "油|水|方便面|泡面|洗衣液|矿泉水|涂料",
  "台": "电视|电脑|洗衣机|空调|冰箱|手机|笔记本|显示器|风扇|电动车",
  "双": "鞋|鞋子|袜子|筷子|手套|拖鞋|球鞋|运动鞋|凉鞋|跑鞋|板鞋|皮鞋",
  "套": "护肤品|化妆品|书|餐具|衣服|沙发|工具|茶具|玩具|教材",
  "斤": "排骨|肉|苹果|香蕉|鸡蛋|菜|鱼|虾|牛肉|猪肉|羊肉|土豆|橘子|葡萄",
  "箱": "苹果|牛奶|矿泉水|方便面|泡面|水果|纸巾|啤酒|饮料|书|衣服|橘子"
};

const QW_CHARS = Object.keys(QW_NOUN).join("");
const NUM = "[0-9零一二两三四五六七八九十百千半几]+";

/* 消费动词：只有出现动词时，其后的量词槽才做判定。
 * 没有动词就不碰量词——「台灯89」里的「台」不是量词，是商品名的一部分。 */
const VERB_RE = /^(?:买|卖|吃|喝|点|花|用|消费|下单|补|充|订)/;

/* 预编译量词白名单正则，避免每次调用重新构造 */
const QW_STRIP_RE = new RegExp("^(?:(" + NUM + ")([" + QW_CHARS + "])|(个)|([" + QW_CHARS + "])(.*)$)");

const bareNumRe = new RegExp("^(" + NUM + ")([" + QW_CHARS + "])");

/**
 * 剥离末尾金额，保留名称部分。
 * "买了一杯咖啡15" → "买了一杯咖啡"
 * "买了一杯咖啡15块" → "买了一杯咖啡"
 */
function splitAmount(text) {
  const m = String(text).match(/^(.*?)\s*[¥￥]?\s*(\d+(?:\.\d+)?)\s*(?:块钱|块|元|钱)?\s*$/);
  if (!m) return { name: String(text).trim(), amount: null };
  return { name: m[1].trim(), amount: Number(m[2]) };
}

/**
 * 核心：在一个已去掉金额的名称片段上，剥掉一层量词槽（如果该剥）。
 * 返回剥离后的名称。不修改入参。
 */
function stripQuantifier(name) {
  let s = String(name).trim();
  if (!s) return s;

  /* 1. 消费动词：没有动词就完全不碰量词 */
  const v = s.match(VERB_RE);
  if (!v) return s;
  s = s.slice(v[0].length);
  if (s.startsWith("了")) s = s.slice(1);          /* 「买了」→ 去掉「了」 */
  if (!s) return s;

  /* 2. (a) 数词 + 量词：无条件剥，剥完名字仍可读 */
  const numQw = s.match(bareNumRe);
  if (numQw) return s.slice(numQw[0].length);

  /* 3. (b) 数词 + 「个」：「一个苹果」→「苹果」 */
  const numGe = s.match(new RegExp("^(" + NUM + ")个"));
  if (numGe) return s.slice(numGe[0].length);

  /* 4. (b) 孤立「个」：剥 */
  if (s.startsWith("个")) return s.slice(1);

  /* 5. (c) 量词 + 品类白名单：命中才剥，否则原样保留 */
  const q = s[0];
  if (QW_NOUN[q]) {
    const tail = s.slice(1);
    if (new RegExp("^(?:" + QW_NOUN[q] + ")").test(tail)) return tail;
    return s;                                       /* 「盒仔茶」走这里 */
  }

  return s;
}

/**
 * 对外入口：输入原始文本，输出 { name, amount }。
 */
function parseItem(text) {
  const { name, amount } = splitAmount(text);
  return { name: stripQuantifier(name), amount };
}

module.exports = { parseItem, stripQuantifier, splitAmount, QW_NOUN };

